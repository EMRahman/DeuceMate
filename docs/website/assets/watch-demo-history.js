/* ==========================================================================
   DeuceMate — Past Matches for the browser watch replica.

   Mirrors MatchHistoryView.swift (the list) and MatchStatsView.swift (the
   drill-down with Resume / End at Current Score, per-set filter, durations,
   steps, calories and the TV-style stats body). Result labels port Core's
   CompactScoreLine. The starter matches are generated by playing real
   scoring-engine matches with a seeded random player, so every score and
   stat is internally consistent. Steps and calories are invented.
   ========================================================================== */
(function () {
  "use strict";
  var S = window.DeuceMateShell;
  if (!S) return;
  var h = S.h, icon = S.icon, api = S.api;
  var Scoring = window.DeuceMateScoring, T = window.DeuceMateTracking, UI = window.DeuceMateStatsUI;

  /* ---- CompactScoreLine / MatchRecord helpers ------------------------------------ */
  function cfgOf(f) { return Scoring.cfgFor(f); }
  function setScoreStr(set, idx, format) {
    var cfg = cfgOf(format);
    if (!cfg.playRegularSets || (Scoring.isDecidingSuperTiebreak(cfg, idx) && set.isTieBreak)) return set.tieBreakPointsMe + "-" + set.tieBreakPointsOpponent;
    if (set.isTieBreak && set.gamesMe + set.gamesOpponent > 0) return set.gamesMe + "-" + set.gamesOpponent + "(" + set.tieBreakPointsMe + "-" + set.tieBreakPointsOpponent + ")";
    if (set.isTieBreak) return set.tieBreakPointsMe + "-" + set.tieBreakPointsOpponent;
    return set.gamesMe + "-" + set.gamesOpponent;
  }
  function completedScore(rec, sep) {
    return rec.sets.map(function (s, i) { return setScoreStr(s, i, rec.format); }).join(sep == null ? "  " : sep);
  }
  function gameScoreString(me, opp) {
    if (!(me > 0 || opp > 0)) return null;
    if (me >= 3 && opp >= 3) return me === opp ? "Deuce" : (me > opp ? "AD–40" : "40–AD");
    var l = ["0", "15", "30", "40"];
    return (l[me] != null ? l[me] : String(me)) + "–" + (l[opp] != null ? l[opp] : String(opp));
  }
  function inProgressScore(rec, sep) {
    if (!rec.sets.length) return null;
    var parts = rec.sets.slice(0, -1).map(function (s, i) { return setScoreStr(s, i, rec.format); });
    var cur = rec.sets[rec.sets.length - 1];
    if (cur.isTieBreak) parts.push("TB " + cur.tieBreakPointsMe + "-" + cur.tieBreakPointsOpponent);
    else {
      parts.push(cur.gamesMe + "-" + cur.gamesOpponent);
      var g = gameScoreString(rec.currentPointsMe, rec.currentPointsOpponent);
      if (g) parts.push("(" + g + ")");
    }
    return parts.length ? parts.join(sep == null ? "  " : sep) : null;
  }
  function isInProgress(rec) { return rec.iWon == null && rec.endTime == null; }
  function resultWord(rec) { return rec.iWon == null ? "Draw" : (rec.iWon ? "Won" : "Lost"); }
  function resultLabel(rec) {
    if (isInProgress(rec)) return inProgressScore(rec) || "In Progress";
    var first = rec.sets[0];
    if (rec.format === "perpetualPoints" && first) return "Final " + setScoreStr(first, 0, rec.format);
    if (rec.format === "superTiebreak" && first) return resultWord(rec) + " " + setScoreStr(first, 0, rec.format);
    if (rec.format === "perpetualSuperTiebreak") {
      var sc = rec.sets.map(function (s, i) { return setScoreStr(s, i, rec.format); });
      var str = sc.length > 4 ? sc.slice(0, 3).join(", ") + ", … (" + sc.length + ")" : sc.join(", ");
      return resultWord(rec) + " " + str;
    }
    return resultWord(rec) + " " + completedScore(rec, ", ");
  }
  /* styledScore: "(7-2)" straight after a digit becomes a superscript. */
  function styled(text) {
    var span = document.createElement("span"), re = /(\d)(\(\d+-\d+\))/g, last = 0, m;
    while ((m = re.exec(text))) {
      span.appendChild(document.createTextNode(text.slice(last, m.index + 1)));
      var sup = document.createElement("sup"); sup.textContent = m[2]; span.appendChild(sup);
      last = m.index + m[0].length;
    }
    span.appendChild(document.createTextNode(text.slice(last)));
    return span;
  }
  var MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  function dateLabel(ms) {
    var d = new Date(ms), p = function (n) { return (n < 10 ? "0" : "") + n; };
    return d.getFullYear() + "-" + MONTHS[d.getMonth()] + "-" + p(d.getDate()) + " " + p(d.getHours()) + ":" + p(d.getMinutes());
  }
  function formatLine(rec) { return S.formatInfo(rec.format).label + (rec.matchType === "doubles" ? " · Doubles" : " · Singles"); }

  /* ==========================================================================
     Starter matches
     ========================================================================== */
  function mulberry32(a) {
    return function () {
      a |= 0; a = (a + 0x6D2B79F5) | 0;
      var t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  function pick(rnd, arr) { return arr[Math.floor(rnd() * arr.length)]; }

  /* Plays a whole match through the real scoring engine. */
  function simulate(o) {
    var rnd = mulberry32(o.seed), state = Scoring.freshState(o.format, o.firstServer || "me");
    var stats = [], momentum = [], played = 0, noTrack = o.format === "perpetualPoints";
    var perSet = {};
    while (!Scoring.isMatchComplete(state) && played < 700) {
      if (o.stopAfter != null && played >= o.stopAfter) break;
      var prev = Scoring.clone(state), server = state.currentServer;
      var pMe = o.bias + (server === "me" ? 0.07 : -0.07);
      var winner = rnd() < pMe ? "me" : "opponent";
      var second = rnd() < 0.34;
      var pending = T.buildPendingPoint(prev, winner, second);
      state = Scoring.pointWon(state, winner).state;
      perSet[pending.setIndex] = (perSet[pending.setIndex] || 0) + 1;
      momentum.push(winner); if (momentum.length > 8) momentum.shift();
      played++;
      if (noTrack) continue;
      if (!o.track) { stats.push(T.buildUncategorizedStat(pending)); continue; }
      var outcome, shot;
      var lostOnSecond = pending.isSecondServe && winner !== pending.server;
      if (lostOnSecond && rnd() < 0.3) { outcome = "doubleFault"; shot = "serve"; }
      else {
        var r = rnd();
        outcome = r < 0.34 ? "winner" : r < 0.6 ? "forcedError" : "unforcedError";
        var opts = T.endingShotOptions(outcome, pending);
        shot = pick(rnd, opts.concat(["rally", "rally"]).filter(function (x) { return opts.indexOf(x) >= 0; }));
      }
      stats.push(T.buildPointStat(pending, outcome, shot));
    }
    var complete = Scoring.isMatchComplete(state);
    var winnerSide = complete ? Scoring.leaderWhenStopped(state) : null;
    var setElapsed = {}, total = 0;
    Object.keys(perSet).forEach(function (k) { setElapsed[k] = Math.round(perSet[k] * (22 + rnd() * 10)); total += setElapsed[k]; });
    var mins = total / 60;
    var start = Date.now() - o.daysAgo * 86400000 - (o.hourOffset || 0) * 3600000;
    return {
      id: "seed" + o.seed, startTime: start, endTime: complete || o.completeAtStop ? start + total * 1000 : null,
      iWon: complete ? (winnerSide ? winnerSide === "me" : null) : null,
      format: o.format, matchType: "singles", sets: state.sets, currentPointsMe: state.currentPointsMe, currentPointsOpponent: state.currentPointsOpponent,
      stats: stats, trackingOn: !!o.track && !noTrack, elapsed: total, setElapsed: setElapsed,
      steps: noTrack ? 0 : Math.round(mins * 36 + played * 4), kcal: noTrack ? 0 : Math.round(mins * 7.6 + played * 0.4), pointsPlayed: played,
      resume: { state: state, momentum: momentum, secondServe: false, trackingEnabled: !!o.track }
    };
  }

  S.seedHistory = function () {
    var seeds = [
      { seed: 2301, format: "bestOf3FullFinalSet", track: true, bias: 0.54, daysAgo: 1, hourOffset: 3, stopAfter: 71 },
      { seed: 1177, format: "standard", track: true, bias: 0.58, daysAgo: 2, hourOffset: 1 },
      { seed: 4410, format: "quick4Games", track: false, bias: 0.46, daysAgo: 3, hourOffset: 5 },
      { seed: 9031, format: "superTiebreak", track: true, bias: 0.6, daysAgo: 4, hourOffset: 2 },
      { seed: 5522, format: "perpetualPoints", track: false, bias: 0.5, daysAgo: 6, hourOffset: 4, stopAfter: 27, completeAtStop: true }
    ];
    S.history = seeds.map(simulate);
  };

  /* ==========================================================================
     History list
     ========================================================================== */
  function recById(id) { for (var i = 0; i < S.history.length; i++) if (S.history[i].id === id) return S.history[i]; return null; }

  function rowFor(rec) {
    var inProg = isInProgress(rec), wrap = h("div", { class: "hist-wrap" });
    var del = h("button", { type: "button", class: "hist-del", "aria-label": "Delete match", onclick: function (e) { e.stopPropagation(); remove(rec); } }, icon("trash", 14), h("span", { text: "Delete" }));
    var tag;
    if (inProg) tag = h("span", { class: "h-tag", text: rec.stats.length + " pts" });
    else if (rec.stats.length) tag = h("span", { class: "h-tag" }, icon("chart", 11), "Match Stats");
    else tag = h("span", { class: "h-tag" }, icon("list", 11), "Score Only");
    var scoreEl = h("div", { class: "h-score" }); scoreEl.appendChild(styled(resultLabel(rec)));
    var row = h("button", { type: "button", class: "hist-row", "aria-label": dateLabel(rec.startTime) + ". " + resultLabel(rec) + ". " + formatLine(rec) },
      h("div", { class: "hr1" }, h("span", { text: dateLabel(rec.startTime) }), inProg ? icon("sync", 11) : null),
      h("div", { class: "hr2" }, h("div", { class: "l" }, scoreEl, h("div", { class: "h-fmt", text: formatLine(rec) })), tag));

    // swipe left to reveal Delete; a long swipe deletes (allowsFullSwipe)
    var startX = null, startY = 0, dx = 0, open = false, moved = false, DEL_W = 84;
    var hideTimer = null;
    function setX(x, anim) {
      row.classList.toggle("dragging", !anim); row.style.transform = "translateX(" + x + "px)";
      clearTimeout(hideTimer);
      if (x < 0) wrap.classList.add("revealed");
      else hideTimer = setTimeout(function () { wrap.classList.remove("revealed"); }, 230);
    }
    row.addEventListener("pointerdown", function (e) { startX = e.clientX; startY = e.clientY; dx = 0; moved = false; });
    row.addEventListener("pointermove", function (e) {
      if (startX == null) return;
      var mx = e.clientX - startX, my = e.clientY - startY;
      if (!moved && (Math.abs(mx) < 6 || Math.abs(my) > Math.abs(mx))) return;
      moved = true;
      try { row.setPointerCapture(e.pointerId); } catch (err) {}
      dx = Math.max(-230, Math.min(0, mx + (open ? -DEL_W : 0)));
      setX(dx, false);
    });
    function end() {
      if (startX == null) return;
      startX = null;
      if (!moved) return;
      if (dx < -170) { remove(rec); return; }
      open = dx < -DEL_W / 2; setX(open ? -DEL_W : 0, true);
    }
    row.addEventListener("pointerup", end);
    row.addEventListener("pointercancel", end);
    row.addEventListener("click", function () {
      if (moved) { moved = false; return; }
      if (open) { open = false; setX(0, true); return; }
      S.push({ id: "detail", recId: rec.id });
    });
    row.addEventListener("keydown", function (e) { if (e.key === "Delete" || e.key === "Backspace") { e.preventDefault(); remove(rec); } });
    wrap.appendChild(del); wrap.appendChild(row);
    return wrap;
  }
  function remove(rec) {
    S.history = S.history.filter(function (r) { return r.id !== rec.id; });
    S.render();
  }

  S.screens.history = function () {
    var scroll = h("div", { class: "app-scroll pad" });
    if (!S.history.length) {
      scroll.appendChild(h("div", { class: "hist-empty" },
        h("div", { class: "a", text: "No past matches yet." }),
        h("div", { class: "b", text: "Finish a match to see it here. Enable Point Outcome Tracking to include full match stats." })));
      return scroll;
    }
    var list = h("div", { class: "hist-list" });
    S.history.forEach(function (rec) { list.appendChild(rowFor(rec)); });
    scroll.appendChild(list);
    scroll.appendChild(h("div", { class: "h-footnote" }, icon("drive", 12),
      h("span", { text: S.history.length + " of " + S.HISTORY_CAP + " on Apple Watch — oldest is replaced as you add more (synced matches stay on iPhone)." })));
    return scroll;
  };

  /* ==========================================================================
     Drill-down (MatchStatsView for a saved record)
     ========================================================================== */
  function resume(rec) {
    function go() {
      if (api.active() && S.liveRecordId() !== rec.id && api.hasProgress()) S.saveLive(false);   // park the other live match first
      api.clear();
      api.restore(rec);
      S.liveId = rec.id; S.headingLocked = true;
      S.popAll();                                   // shouldOpenMatchView: history closes, then the match opens
      setTimeout(function () { S.matchPhase = "play"; S.push({ id: "match" }); }, 450);
    }
    var conflict = api.active() && api.hasProgress() && S.liveRecordId() !== rec.id;
    if (conflict) {
      S.showAlert({ title: "Replace current match?", message: "Your current match will be saved as In Progress so you can resume it later.",
        buttons: [{ label: "Cancel", role: "cancel" }, { label: "Replace", role: "destructive", action: go }] });
    } else go();
  }

  function endAtCurrentScore(rec) {
    S.showAlert({ title: "End at current score?", message: "This marks the match completed and it can no longer be resumed. A tied score is saved as a draw.",
      buttons: [
        { label: "End at Current Score", role: "destructive", action: function () {
          if (api.active() && S.liveRecordId() === rec.id) {
            S.showAlert({ title: "Unable to Complete Match", message: "The saved match could not be updated. Reopen Match History and try again.", buttons: [{ label: "OK", role: "cancel" }] });
            return;
          }
          var leader = Scoring.leaderWhenStopped({ cfg: cfgOf(rec.format), sets: rec.sets, currentPointsMe: rec.currentPointsMe, currentPointsOpponent: rec.currentPointsOpponent });
          rec.endTime = Date.now(); rec.iWon = leader ? leader === "me" : null;
          S.pop();
        } },
        { label: "Cancel", role: "cancel" }]
    });
  }

  var filters = {};   // record id → selected set index | null
  S.screens.detail = function (entry) {
    var rec = recById(entry.recId);
    var scroll = h("div", { class: "app-scroll pad det" });
    if (!rec) { scroll.appendChild(h("div", { class: "hist-empty" }, h("div", { class: "a", text: "Match not found." }))); return scroll; }
    var inProg = isInProgress(rec), hasStats = rec.stats.length > 0;
    var title = inProg ? dateLabel(rec.startTime) : (hasStats ? "Match Stats" : "Score Only Match");
    scroll.appendChild(h("div", { class: "det-title", text: title }));
    scroll.appendChild(h("div", { class: "det-fmt", text: formatLine(rec) }));
    var scoreStr = inProg ? inProgressScore(rec) : completedScore(rec);
    if (scoreStr && rec.sets.length) { var sc = h("div", { class: "det-score" }); sc.appendChild(styled(scoreStr)); scroll.appendChild(sc); }

    if (inProg) {
      scroll.appendChild(h("button", { type: "button", class: "pbtn green", onclick: function () { resume(rec); } }, icon("playfill", 12), "Resume this match"));
      scroll.appendChild(h("button", { type: "button", class: "pbtn gray", onclick: function () { endAtCurrentScore(rec); } }, icon("stopcircle", 13), "End at Current Score"));
    }

    var sel = filters[rec.id] == null ? null : filters[rec.id];
    if (sel != null && sel >= rec.sets.length) sel = null;
    if (hasStats && rec.sets.length > 1) {
      var bar = h("div", { class: "det-filter" });
      [null].concat(rec.sets.map(function (_, i) { return i; })).forEach(function (i) {
        var label = i == null ? "All" : (Scoring.isDecidingSuperTiebreak(cfgOf(rec.format), i) ? "TB" : "S" + (i + 1));
        bar.appendChild(h("button", { type: "button", "aria-pressed": String(sel === i), onclick: function () { filters[rec.id] = i; S.render(); }, text: label }));
      });
      scroll.appendChild(bar);
    }

    // setDurationSection
    var toShow = sel == null ? rec.sets.map(function (_, i) { return i; }) : [sel];
    var hasData = toShow.some(function (i) { return rec.stats.some(function (p) { return p.setIndex === i; }) || rec.setElapsed[i] != null; });
    var hasActivity = (rec.steps || 0) > 0 || (rec.kcal || 0) > 0;
    if ((toShow.length && hasData) || hasActivity) {
      var totalW = 0, weights = {};
      rec.sets.forEach(function (_, i) { weights[i] = Math.max(0, rec.setElapsed[i] || 0); totalW += weights[i]; });
      if (totalW <= 0) { rec.sets.forEach(function (_, i) { weights[i] = rec.stats.filter(function (p) { return p.setIndex === i; }).length; totalW += weights[i]; }); }
      var box = h("div", {});
      toShow.forEach(function (i) {
        var secs = rec.setElapsed[i];
        if (secs == null) {
          var ts = rec.stats.filter(function (p) { return p.setIndex === i; });
          if (!ts.length) return;
          secs = ts.length * 24;
        }
        box.appendChild(kv(toShow.length > 1 ? (Scoring.isDecidingSuperTiebreak(cfgOf(rec.format), i) ? "TB" : "S" + (i + 1)) + " Duration" : "Duration", Math.floor(secs / 60) + " m"));
      });
      var share = sel == null || totalW <= 0 ? 1 : weights[sel] / totalW;
      var steps = Math.round((rec.steps || 0) * share), kcal = Math.round((rec.kcal || 0) * share);
      if (steps > 0) box.appendChild(kv("Steps", steps.toLocaleString("en-US")));
      if (kcal > 0) box.appendChild(kv("Calories", kcal.toLocaleString("en-US") + " kcal"));
      box.appendChild(UI.divider());
      scroll.appendChild(box);
    }

    var body = h("div", { class: "stats-body" });
    if (!hasStats) body.appendChild(UI.empty("Point outcome tracking was off for this match."));
    else {
      var pts = sel == null ? rec.stats : rec.stats.filter(function (p) { return p.setIndex === sel; });
      if (!pts.length) body.appendChild(UI.empty("No tracked points yet."));
      else UI.content(body, pts, rec.matchType);
    }
    scroll.appendChild(body);
    return scroll;
  };
  function kv(a, b) {
    return h("div", { class: "stats-kv" }, h("span", { text: a }), h("span", { class: "v", text: b }));
  }

  S.records = { inProgressScore: inProgressScore, resultLabel: resultLabel };
})();
