    func testPresenterAdvancesOnlyAfterAutomaticResultThenLoadsFreshFixture() {
        var s = WalkthroughSession(step: .unforcedError)
        let firstGeneration = s.generation
        s.advanceAfterResult()
        XCTAssertEqual(s.phase, .situation)
        XCTAssertTrue(s.points.isEmpty)
        s.finishDemonstration()
        XCTAssertEqual(s.phase, .result)
        XCTAssertEqual(s.points.count, 1)
        XCTAssertEqual(s.recentWinners, [.opponent])
        XCTAssertEqual(s.generation, firstGeneration)
        s.advanceAfterResult()
        XCTAssertEqual(s.step, .secondServe)
        XCTAssertEqual(s.phase, .situation)
        XCTAssertNotEqual(s.generation, firstGeneration)
        XCTAssertEqual(s.recentWinners, [.opponent])
        XCTAssertEqual(s.state, WalkthroughFixtures.state(for: .secondServe))
    }
    func testMomentumFollowsScriptedScoreAndUndo() {
        for step in WalkthroughStep.allCases {
            var s = WalkthroughSession(step: step)
            let initial = WalkthroughFixtures.recentWinners(for: step)
            XCTAssertEqual(s.recentWinners, initial)
            let metrics = WalkthroughFixtures.demoMetrics(for: step)
            XCTAssertGreaterThan(metrics.heartRate, 0)
            XCTAssertGreaterThan(metrics.kilocalories, 0)
            XCTAssertGreaterThan(metrics.elapsedSeconds, 0)
            s.finishDemonstration()
            if step == .undoPoint {
                XCTAssertEqual(s.recentWinners, Array(initial.dropLast()))
            } else if step == .findStat || step == .secondServe {
                XCTAssertEqual(s.recentWinners, initial)
            } else if step == .oddSet {
                XCTAssertEqual(s.recentWinners.suffix(2), [.me, .me])
            } else {
                XCTAssertEqual(s.recentWinners.last, step == .losePoint || step == .unforcedError || step == .doubleFault ? .opponent : .me)
            }
            XCTAssertLessThanOrEqual(s.recentWinners.count, 8)
            XCTAssertTrue(s.points.allSatisfy { $0.heartRateBPM == nil && $0.stepsCumulative == nil })
        }
    }
    func testPresenterWaitsThroughCategoryAndFinalCardIsTerminal() {
        var error = WalkthroughSession(step: .unforcedError)
        error.beginExample()
        error.advanceDemonstration(generation: error.generation)
        XCTAssertEqual(error.phase, .outcome)
        error.advanceAfterResult()
        XCTAssertEqual(error.phase, .outcome)
        XCTAssertNotNil(error.pendingPoint)
        error.finishDemonstration()
        XCTAssertEqual(error.phase, .result)
        XCTAssertNil(error.pendingPoint)
        XCTAssertEqual(error.points.count, 1)
        XCTAssertEqual(error.recentWinners, [.opponent])

        var last = WalkthroughSession(step: .oddSet)
        last.advanceAfterResult()
        XCTAssertEqual(last.phase, .situation)
        last.finishDemonstration()
        XCTAssertEqual(last.phase, .result)
        last.advanceAfterResult()
        XCTAssertEqual(last.phase, .done)
        XCTAssertEqual(last.step, .oddSet)
        last.advanceAfterResult()
        XCTAssertEqual(last.phase, .done)
    }
