#!/usr/bin/env node
/* Keep the demo's exported viewer and coaching instructions tied to the native
   sources. No Swift toolchain or project dependencies are needed to regenerate. */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const native = fs.readFileSync(path.join(root, "DeuceMate/Packages/DeuceMateCore/Sources/DeuceMateCore/WebExport/MatchWebTemplate.swift"), "utf8");
const exporter = fs.readFileSync(path.join(root, "DeuceMate/DeuceMate/Export/MatchExporter.swift"), "utf8");
function dedent(text, count) { return text.split("\n").map(line => line.slice(0, count) === " ".repeat(count) ? line.slice(count) : line).join("\n"); }
const source = {};
for (const name of ["head", "css", "js"]) {
  const match = native.match(new RegExp("static let " + name + " = #\\\"\\\"\\\"\\n([\\s\\S]*?)\\n    \\\"\\\"\\\"#"));
  if (!match || match[1].includes("\\#(")) throw new Error("Unsupported native template literal: " + name);
  source[name] = dedent(match[1], 4);
}
source.prompts = {};
for (const [side, name] of [["me", "coachingPrompt"], ["opponent", "opponentCoachingPrompt"]]) {
  const body = exporter.match(new RegExp("private static func " + name + "\\([\\s\\S]*?return \\\"\\\"\\\"\\n([\\s\\S]*?)\\n        \\\"\\\"\\\""));
  const note = exporter.match(new RegExp("private static func " + name + "\\([\\s\\S]*?\\? (\\\"[^\\n]*\\\")"));
  if (!body || !note) throw new Error("Native coaching instructions not found: " + name);
  source.prompts[side] = {
    body: dedent(body[1], 8).replace(/\\\n */g, "").replaceAll("\\(playerNTRP)", "{{level}}").replaceAll("\\(rawPointsNote)", "{{rawPointsNote}}"),
    rawPointsNote: JSON.parse(note[1])
  };
}
const output = "/* Generated by scripts/sync-iphone-demo-exports.cjs from MatchWebTemplate.swift\n   and MatchExporter.swift. Edit the native sources, then regenerate. */\nwindow.DeuceMateNativeExport = " + JSON.stringify(source, null, 2) + ";\n";
const target = path.join(root, "docs/website/assets/phone-demo-native-export.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) throw new Error("Native export snapshot is stale; run node scripts/sync-iphone-demo-exports.cjs");
  process.stdout.write("Native export viewer and coaching instructions are current.\n");
} else { fs.writeFileSync(target, output); process.stdout.write("Updated " + path.relative(root, target) + "\n"); }
