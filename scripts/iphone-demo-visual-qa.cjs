#!/usr/bin/env node
/* Native-reference UI/gesture regression checks for Trends and match reports.
   Uses the external Playwright install; no project dependency is added. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const {pathToFileURL} = require("node:url");
const {chromium, webkit} = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const engine = process.env.PLAYWRIGHT_BROWSER || "chromium";
const output = "/tmp/deucemate-iphone-qa";
async function main() {
  fs.mkdirSync(output, {recursive: true});
  const browser = await (engine === "webkit" ? webkit : chromium).launch({headless: true});
  const context = await browser.newContext({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true, deviceScaleFactor: 1, colorScheme: "light"});
  const page = await context.newPage(), errors = [];
  page.setDefaultTimeout(8000);
  page.on("pageerror", error => errors.push(error.message));
  const root = page.locator("#iphone-demo"), frame = root.locator(".phone-frame");
  const click = async (scope, name) => scope.getByRole("button", {name, exact: true}).click();
  const capture = async name => frame.screenshot({path: path.join(output, `${engine}-${name}.png`)});
  const color = (locator, property) => locator.evaluate((el, key) => getComputedStyle(el)[key], property);
  async function appearance(screen, card, backgroundDark) {
    for (const scheme of ["light", "dark"]) {
      await page.emulateMedia({colorScheme: scheme});
      assert.equal(await color(frame, "colorScheme"), scheme, `${screen} must follow system appearance`);
      assert.equal(await color(root.locator(".phone-body"), "backgroundColor"), scheme === "light" ? "rgb(242, 242, 247)" : backgroundDark, `${screen} needs the native grouped surface`);
      assert.equal(await color(card, "backgroundColor"), scheme === "light" ? "rgb(255, 255, 255)" : screen === "archive" ? "rgb(28, 28, 30)" : "rgb(44, 44, 46)", `${screen} cards must contrast with the grouped background`);
      await root.locator(".phone-body").evaluate(el => {el.scrollTop = 0;}); await capture(`${screen}-${scheme}`);
    }
    await page.emulateMedia({colorScheme: "light"});
  }
  try {
    await page.goto(process.env.PLAYWRIGHT_URL || pathToFileURL(path.resolve(__dirname, "../docs/website/try.html")).href);
    const uncategorizedRecord = await page.evaluate(() => window.DeuceMatePhone.records().find(r => r.endTime && r.stats.length && r.stats.every(p => p.outcome === "uncategorized")));
    if (uncategorizedRecord) assert.equal(await root.locator(`.phone-match-wrap[data-match-id="${uncategorizedRecord.id}"] .phone-row-badge`).first().innerText(), "Stats", "native archive Stats badge depends on point history, independently of outcome categorization");
    await appearance("archive", root.locator(".phone-trends-card"), "rgb(0, 0, 0)");
    assert.equal(await color(root.locator(".phone-row-score").first(), "color"), "rgb(0, 0, 0)", "light archive scores must use native primary black text");
    await click(root.locator(".phone-body"), "☁ iCloud unavailable — stored on iPhone ›");
    const guide = root.locator(".phone-dialog");
    for (const scheme of ["light", "dark", "light"]) {
      await page.emulateMedia({colorScheme: scheme});
      await page.waitForFunction(scheme => document.querySelector(".phone-dialog").dataset.appearance === scheme, scheme);
      assert.equal(await color(guide, "color"), scheme === "light" ? "rgb(0, 0, 0)" : "rgb(245, 245, 247)", "open popups must adapt without dismissal when system appearance changes");
      await capture(`icloud-guide-${scheme}`);
    }
    await click(guide, "Done");
    await click(root.locator(".phone-nav"), "Settings");
    await appearance("settings", root.locator(".phone-settings .phone-card").first(), "rgb(28, 28, 30)");
    const settingsTitle = await root.locator(".phone-nav>strong").boundingBox(), settingsDone = await root.locator(".phone-nav").getByRole("button", {name: "Back to Matches", exact: true}).boundingBox();
    assert.ok(settingsDone.x > settingsTitle.x, "Settings sheet must place Done on the native trailing side");
    assert.equal(await color(root.locator(".phone-setting-copy strong").first(), "color"), "rgb(0, 0, 0)");
    assert.equal(await color(root.locator(".phone-theme-tile").first(), "color"), "rgb(255, 255, 255)", "court theme previews keep their native dark palette");
    await click(root.locator(".phone-nav"), "Back to Matches");
    await click(root.locator(".phone-nav"), "Manual match entry");
    await appearance("manual", root.locator(".phone-manual .phone-card").first(), "rgb(28, 28, 30)");
    await click(root.locator(".phone-nav"), "Cancel");
    await click(root, "Performance Trends");
    const trends = root.locator(".pr-trends"), filters = trends.locator(".pr-trend-filters");
    assert.equal(await filters.locator("select").count(), 1, "only the native format menu uses a select; window/type/display are segments");
    for (const name of ["Trend window", "Match type", "Display"]) assert.equal(await filters.getByRole("group", {name, exact: true}).count(), 1);
    const groups = await trends.locator(".pr-trend-section-title").allTextContents();
    assert.deepEqual(groups.slice(0, 3), ["Errors", "Serve & Return", "Attack"]);
    const errorSection = trends.locator('[data-group="Errors"]');
    assert.ok(await errorSection.locator('path[d*="C"]').count() > 0, "native trend lines must use smooth monotone curves");
    assert.ok(await errorSection.locator('svg text[x="303"]').count() > 0, "percentage axis must sit on the right");
    const df = errorSection.getByRole("button", {name: "Double Faults", exact: true});
    await df.click(); assert.equal(await df.getAttribute("aria-pressed"), "false");
    await df.click(); assert.equal(await df.getAttribute("aria-pressed"), "true");
    assert.equal(await errorSection.getByRole("button", {name: "Double Faults Conceded", exact: true}).getAttribute("aria-pressed"), "false");
    await root.locator(".phone-body").evaluate(el => {el.scrollTop = 0;}); await capture("trends-light");
    const chart = errorSection.locator(".pr-trend-chart"); await chart.scrollIntoViewIfNeeded();
    const box = await chart.boundingBox(); await page.touchscreen.tap(box.x + box.width * .55, box.y + box.height * .45);
    assert.ok(await errorSection.locator(".pr-trend-selection").isVisible(), "touching a trend must reveal the selected match date and values");
    await chart.focus(); await page.keyboard.press("End");
    assert.ok((await errorSection.locator(".pr-trend-selection").innerText()).length > 8);
    await trends.locator('[data-group="Serve & Return"]').scrollIntoViewIfNeeded(); await capture("trends-serving");
    await page.emulateMedia({colorScheme: "dark"}); await root.locator(".phone-body").evaluate(el => {el.scrollTop = 0;}); await capture("trends-dark");
    assert.equal(await frame.evaluate(el => getComputedStyle(el).colorScheme), "dark");
    await page.emulateMedia({colorScheme: "light"});
    await click(root, "Back to Matches");
    const record = await page.evaluate(() => window.DeuceMatePhone.records().find(r => r.endTime && r.sets.length >= 2 && r.stats.length && r.stats.every(p => p.outcome !== "uncategorized")));
    assert.ok(record, "a fully tracked multi-set report fixture is required");
    await root.locator(`.phone-match-wrap[data-match-id="${record.id}"] .phone-match-row`).click();
    await appearance("detail", root.locator(".pr-hero"), "rgb(28, 28, 30)");
    assert.equal(await color(root.locator(".pr-score"), "color"), "rgb(0, 0, 0)");
    assert.equal(await color(root.locator(".pr-native-graph .pr-chart-svg text").first(), "fill"), "rgb(142, 142, 147)", "chart axes must remain legible on the light plot");
    const stats = root.locator(".pr-stats");
    const headings = await stats.locator(".pr-native-section-title").allTextContents();
    assert.equal(headings[0], "Duration");
    assert.ok(headings.findIndex(t => t.includes("Coaching Insights")) < headings.findIndex(t => t.includes("Outcome Breakdown")));
    assert.ok(headings.findIndex(t => t.includes("Pulse Coach")) < headings.findIndex(t => t.includes("Outcome Breakdown")));
    assert.equal(await stats.locator(".pr-metrics").count(), 0, "report must use native sections instead of dashboard metric tiles");
    assert.equal(await root.locator(".pr-export-group").count(), 0, "sharing belongs in the toolbar, outside report content");
    const setPicker = stats.getByRole("group", {name: "Set", exact: true}); await click(setPicker, "Set 1");
    const expected = await page.evaluate(record => window.DeuceMateTracking.matchStatsSummary(record.stats.filter(p => p.setIndex === 0), "me"), record);
    const winners = stats.locator('[data-stat="Winners"]');
    assert.equal(await winners.locator(".pr-split-value.pr-me").innerText(), String(expected.myWinners), "set filter must recompute the native count bar");
    assert.ok((await root.locator(".pr-pw-me").innerText()).includes(String(expected.pointsWon)));
    await stats.locator(".pr-native-section").first().scrollIntoViewIfNeeded(); await capture("report-duration-coaching");
    await winners.scrollIntoViewIfNeeded(); await capture("report-comparisons");
    await click(root, "Points");
    assert.equal(await root.locator(".pr-points .pr-native-section").count(), new Set(record.stats.map(p => p.setIndex)).size, "Points must include every set independent of the Stats set picker");
    assert.equal(await root.locator(".pr-points .pr-point-row").count(), record.stats.length);
    await root.locator(".pr-points").scrollIntoViewIfNeeded(); await capture("report-points");
    const selectedIndex = record.stats.findIndex(p => p.setIndex === 1), selectedPoint = record.stats[selectedIndex];
    assert.ok(selectedIndex > 0 && selectedPoint.gameScoreAtStart.server === 0 && selectedPoint.gameScoreAtStart.returner === 0, "inspector fixture must begin a fresh second-set game");
    const inspect = root.getByRole("button", {name: "Inspect point " + (selectedIndex + 1), exact: true});
    await inspect.focus(); await page.keyboard.press("Enter");
    const inlineInspector = root.locator(".pr-native-graph .pr-inspector"), through = record.stats.slice(0, selectedIndex + 1), meTotal = through.filter(p => p.winner === "me").length;
    assert.equal(await inlineInspector.locator("strong").innerText(), "Set 2 · Pt 1", "graph inspector must reset its point number at the new set");
    assert.equal(await inlineInspector.locator(".pr-me").innerText(), "● Me " + meTotal);
    assert.equal(await inlineInspector.locator(".pr-opp").innerText(), "● Opp " + (through.length - meTotal), "selection totals must include the inspected rally");
    assert.equal(await inlineInspector.locator(".pr-inspector-badge").count(), 0, "unfiltered native inspector must not invent an outcome badge");
    assert.ok((await inlineInspector.innerText()).includes("After point: " + (selectedPoint.winner === "me" ? "15–0" : "0–15")), "inspector must show the game after this rally, not its saved 0–0 starting score");
    const stepDelta = selectedPoint.stepsCumulative - record.stats[selectedIndex - 1].stepsCumulative;
    assert.ok((await inlineInspector.innerText()).includes(stepDelta + " steps"), "inspector must show movement for the selected point");
    await inlineInspector.scrollIntoViewIfNeeded(); await capture("report-inspector");
    await click(root, "Stats"); await click(root, "Expand graph");
    const dialog = root.locator(".phone-graph-dialog"), panel = dialog.locator(".pr-expanded-graph"), stage = panel.locator(".pr-expanded-stage");
    async function fits() {
      await page.waitForFunction(() => {
        const device = document.querySelector('.phone-frame').getBoundingClientRect(), sheet = document.querySelector('.phone-graph-dialog').getBoundingClientRect();
        return sheet.x >= device.x && sheet.y >= device.y && sheet.right <= device.right + 1 && sheet.bottom <= device.bottom + 1;
      });
      const [device, sheet] = await Promise.all([frame.boundingBox(), dialog.boundingBox()]);
      assert.ok(sheet.x >= device.x && sheet.y >= device.y && sheet.x + sheet.width <= device.x + device.width + 1 && sheet.y + sheet.height <= device.y + device.height + 1, "expanded graph must fit entirely inside the iPhone frame");
      const [graph, controls] = await Promise.all([stage.boundingBox(), panel.locator(".pr-expanded-controls").boundingBox()]);
      assert.ok(graph.height >= 100 && controls.height >= 100, "chart and independently scrolling controls must both remain usable");
      assert.ok(graph.y + graph.height <= controls.y + 2, "graph controls must not overlap the chart");
    }
    await fits();
    assert.equal(await dialog.locator(".pr-inspector-totals").count(), 1, "expanded graph must show the selected cumulative totals only once");
    assert.equal((await stage.locator('svg text[x="2"]').allTextContents()).at(-1), "60", "the native 58-point fixture must use a readable 60-point axis ceiling");
    await dialog.getByLabel("Heart Rate", {exact: true}).check();
    await dialog.getByLabel("Steps", {exact: true}).check();
    assert.ok(await stage.locator('text[data-axis="bpm"]').count() > 0 && await stage.locator('text[data-axis="steps"]').count() > 0, "both active overlays must expose their native secondary axes");
    assert.ok(await stage.locator('polyline[stroke="#ff3b30b3"]').count() > 0, "heart-rate overlay must use native red");
    assert.ok(await stage.locator('polyline[stroke="#34c759bf"][stroke-dasharray]').count() > 0, "steps must use the native dashed green line");
    assert.equal(await dialog.locator(".pr-chart-legend .pr-legend-hr").innerText(), "Heart Rate");
    assert.equal(await dialog.locator(".pr-chart-legend .pr-legend-steps").innerText(), "Steps");
    for (const scheme of ["light", "dark", "light"]) {
      await page.emulateMedia({colorScheme: scheme});
      await page.waitForFunction(scheme => document.querySelector(".phone-graph-dialog").dataset.appearance === scheme, scheme);
      assert.equal(await color(dialog, "backgroundColor"), scheme === "light" ? "rgb(255, 255, 255)" : "rgb(0, 0, 0)", "expanded graph uses the native full-screen system canvas");
      assert.equal(await color(stage.locator(".pr-chart-svg text").first(), "fill"), scheme === "light" ? "rgb(142, 142, 147)" : "rgb(164, 165, 168)");
      assert.match(await color(stage.locator('text[data-axis="bpm"]').first(), "fill"), /^rgba?\(255,\s*59,\s*48(?:,|\))/, "heart-rate axis must stay native red in both appearances");
      assert.match(await color(stage.locator('text[data-axis="steps"]').first(), "fill"), /^rgba?\(52,\s*199,\s*89(?:,|\))/, "steps axis must stay native green in both appearances");
      await capture(`expanded-${scheme}`);
    }
    await capture("expanded-overlays");
    await dialog.getByLabel("Heart Rate", {exact: true}).uncheck();
    await dialog.getByLabel("Steps", {exact: true}).uncheck();
    await capture("expanded-graph");
    assert.equal(await panel.getAttribute("data-visible-points"), String(record.stats.length));
    if (engine !== "webkit") {
      const cdp = await context.newCDPSession(page), bounds = await stage.boundingBox(), cx = bounds.x + bounds.width * .5, cy = bounds.y + bounds.height * .5;
      const point = (id, x) => ({id, x, y: cy, radiusX: 2, radiusY: 2});
      await cdp.send("Input.dispatchTouchEvent", {type: "touchStart", touchPoints: [point(0, cx - 20), point(1, cx + 20)]});
      await cdp.send("Input.dispatchTouchEvent", {type: "touchMove", touchPoints: [point(0, cx - 60), point(1, cx + 60)]});
      await cdp.send("Input.dispatchTouchEvent", {type: "touchEnd", touchPoints: []});
      assert.ok(Number(await panel.getAttribute("data-visible-points")) < record.stats.length / 2, "real two-finger pinch must zoom the chart");
      await cdp.detach();
    } else { await stage.locator("svg").focus(); await page.keyboard.press("+"); }
    const start = Number(await panel.getAttribute("data-pan-start")), bounds = await stage.boundingBox();
    await page.mouse.move(bounds.x + bounds.width * .65, bounds.y + bounds.height * .45); await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width * .35, bounds.y + bounds.height * .45, {steps: 6}); await page.mouse.up();
    assert.ok(Number(await panel.getAttribute("data-pan-start")) > start, "dragging a zoomed chart must pan its point window");
    await page.mouse.dblclick(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5);
    assert.equal(await panel.getAttribute("data-visible-points"), String(record.stats.length), "double tap/click must restore the full point range");
    const wonPreset = dialog.getByRole("button", {name: /^Points Won /}), lostPreset = dialog.getByRole("button", {name: /^Points Lost /});
    await wonPreset.click(); assert.equal(await wonPreset.getAttribute("aria-pressed"), "true");
    const symbolMap = {winner: "circle", doubleFault: "square", unforcedError: "cross", forcedError: "triangle"};
    const expectedSymbols = [...new Set(record.stats.filter(p => p.winner === "me").map(p => symbolMap[p.outcome]))].sort();
    assert.ok(expectedSymbols.some(s => s !== "circle"), "Points Won fixture must include an opponent error");
    assert.deepEqual(await stage.locator(".pr-chart-mark").evaluateAll(nodes => [...new Set(nodes.map(n => n.dataset.symbol))].sort()), expectedSymbols, "rendered outcome markers must use category-specific native shapes");
    assert.equal(await stage.locator(".pr-chart-mark").evaluateAll(nodes => nodes.every(n => n.tagName === ({circle: "circle", square: "rect", cross: "path", triangle: "polygon"})[n.dataset.symbol])), true, "shape labels must correspond to actual SVG geometry");
    assert.equal(await stage.locator('.pr-chart-mark[data-symbol="circle"]').first().getAttribute("fill"), "#FFCC00", "winner symbols must use the native system yellow");
    assert.equal(await stage.locator('.pr-chart-mark[data-symbol="square"]').first().getAttribute("fill"), "#FF9500", "double faults must use native orange");
    const selectedError = record.stats.findIndex(p => p.winner === "me" && p.outcome === "unforcedError");
    assert.ok(selectedError >= 0, "fixture must include an opponent unforced error");
    await stage.getByRole("button", {name: "Inspect point " + (selectedError + 1), exact: true}).focus(); await page.keyboard.press("Enter");
    assert.deepEqual(await dialog.locator(".pr-inspector-badge").allTextContents(), ["Opp UE"], "inspector badge must follow the active outcome filter and actor");
    await capture("expanded-outcome-symbols");
    await lostPreset.click(); assert.equal(await wonPreset.getAttribute("aria-pressed"), "false");
    assert.equal(await lostPreset.getAttribute("aria-pressed"), "true", "native Points Won/Lost quick selections must be mutually exclusive");
    assert.equal(await dialog.locator(".pr-inspector-badge").count(), 0, "a selected won rally must not retain its badge under Points Lost");
    await lostPreset.click();
    const secondServe = dialog.locator(".pr-chip").filter({hasText: /^2nd Serve [1-9]/}).first();
    await secondServe.click();
    assert.ok(await stage.locator('.pr-chart-mark[data-symbol="asterisk"]').count() > 0, "second-serve filtering must render native asterisk markers");
    assert.equal(await stage.locator('.pr-chart-mark:not([data-symbol="asterisk"])').count(), 0);
    await capture("expanded-serving-symbols"); await secondServe.click();
    const allWon = dialog.getByRole("button", {name: /^All Won /}), allLost = dialog.getByRole("button", {name: /^All Lost /});
    await allWon.click();
    const shotSymbols = {serve: "pentagon", return: "asterisk", servePlusOne: "plus", rally: "triangle"};
    assert.deepEqual(await stage.locator(".pr-chart-mark").evaluateAll(nodes => [...new Set(nodes.map(n => n.dataset.symbol))].sort()), [...new Set(record.stats.filter(p => p.winner === "me" && p.endingShot).map(p => shotSymbols[p.endingShot]))].sort(), "ending-shot markers must use native pentagon/asterisk/plus/triangle symbols");
    await capture("expanded-ending-symbols");
    await allLost.click();
    assert.equal(await allWon.getAttribute("aria-pressed"), "false");
    assert.equal(await allLost.getAttribute("aria-pressed"), "true", "native ending-shot quick selections must be mutually exclusive");
    await allLost.click();
    const pill = dialog.locator(".pr-chip").filter({hasText: /^W [1-9]/}).first(); await pill.click(); assert.equal(await pill.getAttribute("aria-pressed"), "true");
    await stage.locator("svg").focus(); await page.keyboard.press("+"); await click(dialog, "Reset Zoom");
    const stageBefore = await stage.boundingBox(); await panel.locator(".pr-expanded-controls").evaluate(el => {el.scrollTop = el.scrollHeight;});
    assert.deepEqual(await stage.boundingBox(), stageBefore, "scrolling graph filters must leave the chart fixed in place");
    await fits(); await capture("expanded-controls");
    await page.setViewportSize({width: 320, height: 740}); await fits(); await capture("expanded-narrow");
    await page.setViewportSize({width: 1280, height: 900}); await fits(); await capture("expanded-desktop");
    await click(dialog, "Done");
    assert.equal(await root.locator(".pr-native-graph .pr-chip").count(), 0, "expanded filters must not leak into the inline chart");
    await click(root, "Expand graph");
    assert.equal(await dialog.locator(".pr-chip[aria-pressed=true]").count(), 1, "graph filter choices must survive reopening");
    await click(dialog, "Done");
    await click(root.locator(".phone-nav"), "Back to Matches");
    const scoreOnly = await page.evaluate(() => window.DeuceMatePhone.records().find(r => r.endTime && !r.stats.length));
    assert.ok(scoreOnly, "native score-only empty-state fixture is required");
    await root.locator(`.phone-match-wrap[data-match-id="${scoreOnly.id}"] .phone-match-row`).click();
    const emptyGraph = root.locator(".pr-empty-graph");
    assert.equal(await emptyGraph.locator("strong").innerText(), "No Points to Graph");
    assert.equal(await emptyGraph.locator(".phone-icon").count(), 1, "empty graph must retain its native chart icon");
    assert.equal(await root.locator(".pr-tabs").count(), 0, "empty point history must not expose a blank Points tab");
    assert.equal(await root.locator(".pr-stats .pr-native-section-title").isVisible(), false, "native missing-statistics message has no extra Statistics heading");
    await appearance("score-only", root.locator(".pr-hero"), "rgb(28, 28, 30)");
    assert.equal(await color(emptyGraph, "backgroundColor"), "rgb(255, 255, 255)");
    assert.ok((await emptyGraph.boundingBox()).height >= 100, "native empty graph needs a full grouped card");
    assert.deepEqual(errors, [], "native-style screens must not emit runtime errors");
    process.stdout.write(`Native Trends/report/expanded-graph UI QA passed (${engine}). Screenshots: ${output}\n`);
  } finally { await context.close(); await browser.close(); }
}
main().catch(error => {console.error(error); process.exitCode = 1;});
